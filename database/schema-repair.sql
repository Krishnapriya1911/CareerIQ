create or replace function public.book_mentor_session(p_mentor_id bigint,p_minutes integer,p_scheduled_at timestamptz,p_notes text)
returns public.mentor_sessions language plpgsql security definer set search_path='' as $$
declare student public.users; mentor public.mentors; result public.mentor_sessions; cost integer;
begin
 if auth.uid() is null then raise exception 'Sign in required' using errcode='42501'; end if;
 cost=case p_minutes when 10 then 10 when 30 then 20 when 45 then 35 else null end;
 if cost is null or p_scheduled_at<=now() or p_scheduled_at is null or length(trim(coalesce(p_notes,'')))=0 then raise exception 'Invalid booking details'; end if;
 select * into student from public.users where auth_uid=auth.uid() for update;
 if not found then raise exception 'Student profile required'; end if;
 select * into mentor from public.mentors where id=p_mentor_id and availability;
 if not found then raise exception 'Mentor unavailable'; end if;
 if student."remainingCredits"<cost then raise exception 'Not enough credits'; end if;
 update public.users set "remainingCredits"="remainingCredits"-cost where id=student.id;
 insert into public.mentor_sessions(mentor_id,student_id,"mentorName","mentorAvatar",session_type,scheduled_at,notes)
 values(mentor.id,student.id,mentor.full_name,mentor.avatar,p_minutes||' min session',p_scheduled_at,p_notes) returning * into result;
 return result;
end $$;
revoke all on function public.book_mentor_session(bigint,integer,timestamptz,text) from public,anon;
