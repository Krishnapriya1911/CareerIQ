-- CareerIQ: additive schema repair and owner-scoped access for the existing project.
-- Run as the project database administrator. Existing profile IDs and user data survive.
begin;
create schema if not exists careeriq_private;
revoke all on schema careeriq_private from public, anon, authenticated;

alter table public.users add column if not exists auth_uid uuid references auth.users(id) on delete cascade default auth.uid();
alter table public.mentors add column if not exists auth_uid uuid references auth.users(id) on delete cascade default auth.uid();
do $$ begin
 if exists(select 1 from public.users u where u.auth_uid is null and
   (select count(*) from auth.users a where lower(a.email)=lower(u."userEmail"))<>1)
 or exists(select 1 from public.mentors m where m.auth_uid is null and
   (select count(*) from auth.users a where lower(a.email)=lower(m.email))<>1) then
  raise exception 'Legacy ownership must match exactly one authentication account';
 end if;
end $$;
update public.users u set auth_uid=a.id from auth.users a where u.auth_uid is null and lower(u."userEmail")=lower(a.email);
update public.mentors m set auth_uid=a.id from auth.users a where m.auth_uid is null and lower(m.email)=lower(a.email);
-- Fail, rather than guessing ownership, when a legacy profile cannot be matched.
alter table public.users alter column auth_uid set not null;
alter table public.mentors alter column auth_uid set not null;
create unique index if not exists users_auth_uid_key on public.users(auth_uid);
create unique index if not exists mentors_auth_uid_key on public.mentors(auth_uid);
alter table public."userCalendar" add column if not exists title text not null default 'Untitled event';
alter table public."userCalendar" add column if not exists google_event_id text;

create table if not exists public."roadmapUsers" (
 id bigint generated by default as identity primary key,
 user_id bigint not null references public.users(id) on delete cascade,
 roadmap_data jsonb not null, mode text, timeline text,
 "isStarted" boolean not null default false,
 status text not null default 'not_started', progress integer not null default 0 check(progress between 0 and 100),
 created_at timestamptz not null default now()
);
create table if not exists public.tracks (
 id bigint generated by default as identity primary key,
 roadmap_id bigint not null unique references public."roadmapUsers"(id) on delete cascade,
 user_id bigint not null references public.users(id) on delete cascade,
 checkpoints jsonb not null default '[]'::jsonb check(jsonb_typeof(checkpoints)='array'),
 created_at timestamptz not null default now()
);
create table if not exists public.others (
 id bigint generated by default as identity primary key,
 "userId" bigint not null references public.users(id) on delete cascade,
 "jobTitle" text not null, "interviewInsights" jsonb not null,
 created_at timestamptz not null default now()
);
create table if not exists public.mentor_sessions (
 id bigint generated by default as identity primary key,
 mentor_id bigint not null references public.mentors(id),
 student_id bigint not null references public.users(id),
 "mentorName" text, "mentorAvatar" text,
 session_type text not null check(session_type in ('10 min session','30 min session','45 min session')),
 status text not null default 'pending' check(status in ('pending','accepted','rejected','completed')),
 requested_at timestamptz not null default now(), scheduled_at timestamptz,
 completed_at timestamptz, notes text, vc_link text, reviews text
);

-- Social discovery reads a deliberately limited directory, never private account rows.
create table if not exists public.users_directory (
 id bigint primary key references public.users(id) on delete cascade,
 "userName" text, avatar text, "institutionName" text, "mainFocus" text,
 current_status text, "selectedCareer" text,
 "userEmail" text generated always as (null::text) stored,
 created_at timestamptz
);
create table if not exists public.mentors_directory (
 id bigint primary key references public.mentors(id) on delete cascade,
 full_name text, avatar text, expertise text[], current_position text,
 availability boolean, rating numeric, linkedin text, bio text, video_url text,
 is_verified boolean, created_at timestamptz,
 email text generated always as (null::text) stored,
 phone text generated always as (null::text) stored
);
create or replace function careeriq_private.sync_directory() returns trigger
language plpgsql security definer set search_path='' as $$
begin
 if tg_table_name='users' then
  insert into public.users_directory(id,"userName",avatar,"institutionName","mainFocus",current_status,created_at)
  values(new.id,new."userName",new.avatar,new."institutionName",new."mainFocus",new.current_status,new.created_at)
  on conflict(id) do update set "userName"=excluded."userName",avatar=excluded.avatar,
   "institutionName"=excluded."institutionName","mainFocus"=excluded."mainFocus",current_status=excluded.current_status;
 elsif tg_table_name='mentors' then
  insert into public.mentors_directory(id,full_name,avatar,expertise,current_position,availability,rating,linkedin,bio,video_url,is_verified,created_at)
  values(new.id,new.full_name,new.avatar,new.expertise,new.current_position,new.availability,new.rating,new.linkedin,new.bio,new.video_url,new.is_verified,new.created_at)
  on conflict(id) do update set full_name=excluded.full_name,avatar=excluded.avatar,expertise=excluded.expertise,
   current_position=excluded.current_position,availability=excluded.availability,rating=excluded.rating,
   linkedin=excluded.linkedin,bio=excluded.bio,video_url=excluded.video_url,is_verified=excluded.is_verified;
 else
  update public.users_directory set "selectedCareer"=new."selectedCareer" where id=new."userId";
 end if;
 return new;
end $$;
revoke all on function careeriq_private.sync_directory() from public,anon,authenticated;
drop trigger if exists careeriq_directory_sync on public.users;
create trigger careeriq_directory_sync after insert or update on public.users for each row execute function careeriq_private.sync_directory();
drop trigger if exists careeriq_directory_sync on public.mentors;
create trigger careeriq_directory_sync after insert or update on public.mentors for each row execute function careeriq_private.sync_directory();
drop trigger if exists careeriq_quiz_directory_sync on public."userQuizData";
create trigger careeriq_quiz_directory_sync after insert or update on public."userQuizData" for each row execute function careeriq_private.sync_directory();
insert into public.users_directory(id,"userName",avatar,"institutionName","mainFocus",current_status,created_at)
 select id,"userName",avatar,"institutionName","mainFocus",current_status,created_at from public.users
 on conflict(id) do nothing;
insert into public.mentors_directory(id,full_name,avatar,expertise,current_position,availability,rating,linkedin,bio,video_url,is_verified,created_at)
 select id,full_name,avatar,expertise,current_position,availability,rating,linkedin,bio,video_url,is_verified,created_at from public.mentors
 on conflict(id) do nothing;

-- Backfill the safe career label for existing profiles too.
update public.users_directory d set "selectedCareer"=q."selectedCareer"
from (select distinct on ("userId") "userId","selectedCareer" from public."userQuizData" order by "userId",created_at desc,id desc) q
where d.id=q."userId";

-- Make message participants unambiguous even when student and mentor numeric IDs overlap.
do $$ begin
 if not exists(select 1 from information_schema.columns where table_schema='public' and table_name='messages' and column_name='sender_auth_uid')
    and exists(select 1 from public.messages) then
  raise exception 'Existing messages require an explicit participant migration before this repair.';
 end if;
end $$;
alter table public.messages add column if not exists sender_type text not null default 'peer' check(sender_type in ('peer','mentor'));
alter table public.messages add column if not exists sender_auth_uid uuid not null references auth.users(id);
alter table public.messages add column if not exists receiver_auth_uid uuid not null references auth.users(id);
create or replace function careeriq_private.message_participants() returns trigger
language plpgsql security definer set search_path='' as $$
declare sender_uid uuid; recipient_uid uuid;
begin
 if new.sender_type='peer' then select auth_uid into sender_uid from public.users where id=new.sender_id;
 else select auth_uid into sender_uid from public.mentors where id=new.sender_id; end if;
 if sender_uid is distinct from auth.uid() then raise exception 'Sender is not the signed-in account' using errcode='42501'; end if;
 if tg_op='UPDATE' and (new.sender_id,new.receiver_id,new.sender_type,new.receiver_type) is distinct from (old.sender_id,old.receiver_id,old.sender_type,old.receiver_type) then
  raise exception 'Message participants cannot be changed' using errcode='42501';
 end if;
 if new.receiver_type='peer' then select auth_uid into recipient_uid from public.users where id=new.receiver_id;
 else select auth_uid into recipient_uid from public.mentors where id=new.receiver_id; end if;
 if recipient_uid is null or length(trim(new.content))=0 or length(new.content)>10000 then raise exception 'Invalid recipient or message'; end if;
 new.sender_auth_uid=sender_uid;new.receiver_auth_uid=recipient_uid;
 return new;
end $$;
revoke all on function careeriq_private.message_participants() from public,anon,authenticated;
drop trigger if exists careeriq_message_participants on public.messages;
create trigger careeriq_message_participants before insert or update on public.messages for each row execute function careeriq_private.message_participants();

-- Replace the earlier authenticated=true policies only on CareerIQ's named tables.
do $$ declare t text; p record; begin
 foreach t in array array['users','mentors','users_directory','mentors_directory','userQuizData','notification','userCalendar','messages','job_tracker','colleges','roadmapUsers','tracks','others','mentor_sessions'] loop
  execute format('alter table public.%I enable row level security',t);
  execute format('revoke all on table public.%I from public,anon,authenticated',t);
  for p in select policyname from pg_policies where schemaname='public' and tablename=t loop
   execute format('drop policy %I on public.%I',p.policyname,t);
  end loop;
 end loop;
end $$;
